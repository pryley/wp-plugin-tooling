<?php

test('a stub keeps only the symbols its manifest entry lists', function () {
    $dir = scratch('stubs');

    $run = runBin('generate-stubs', $dir);

    $stub = (string) file_get_contents("{$dir}/tests/stubs/fixture.php");
    expect($run['code'])->toBe(0)
        ->and($stub)->toContain('function fixture_answer(int $question): int')
        ->and($stub)->toContain("define('FIXTURE_VERSION', '9.9.9')")
        ->and($stub)->not->toContain('fixture_other')
        ->and($stub)->not->toContain('Fixture_Class')
        ->and($stub)->toContain('do not edit, rerun `make stubs:update`.');
});

test('the manifest and the output folder resolve from the working directory', function () {
    $dir = scratch('stubs');
    mkdir("{$dir}/config");
    rename("{$dir}/tests/bin/stubs-manifest.php", "{$dir}/config/stubs.php");

    $run = runBin('generate-stubs', $dir, ['--manifest=config/stubs.php', '--out=build/stubs']);

    expect($run['code'])->toBe(0)
        ->and("{$dir}/build/stubs/fixture.php")->toBeFile();
});

test('a hand-written file in the stubs folder is never overwritten', function () {
    $dir = scratch('stubs');
    mkdir("{$dir}/tests/stubs", 0777, true);
    file_put_contents("{$dir}/tests/stubs/fixture.php", "<?php\n// a working fake\n");

    $run = runBin('generate-stubs', $dir);

    expect($run['code'])->toBe(1)
        ->and($run['output'])->toContain('tests/stubs/fixture.php is hand-written')
        ->and(file_get_contents("{$dir}/tests/stubs/fixture.php"))->toBe("<?php\n// a working fake\n");
});

test('a stub written by the generator before it moved here is regenerated', function () {
    $dir = scratch('stubs');
    mkdir("{$dir}/tests/stubs", 0777, true);
    file_put_contents("{$dir}/tests/stubs/fixture.php", implode("\n", [
        '<?php',
        '',
        '/**',
        ' * fixture 1.0.0',
        ' * Generated by tests/bin/generate-stubs.php — do not edit, rerun `make stubs:update`.',
        ' */',
        '',
    ]));

    $run = runBin('generate-stubs', $dir);

    expect($run['code'])->toBe(0)
        ->and(file_get_contents("{$dir}/tests/stubs/fixture.php"))->toContain('function fixture_answer');
});

test('a stub that cannot be written fails the run', function () {
    $dir = scratch('stubs');
    file_put_contents("{$dir}/blocker", ''); // a file where the output folder should be

    $run = runBin('generate-stubs', $dir, ['--out=blocker']);

    expect($run['code'])->toBe(1)
        ->and($run['output'])->toContain('could not write');
});
